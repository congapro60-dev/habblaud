function terminology(key: string, value: string): string {
  let out = value;
  if (/agents?\b/i.test(EN[key] ?? key)) {
    out = out.replaceAll('Đại lý phụ', 'Tác nhân phụ').replaceAll('đại lý phụ', 'tác nhân phụ')
      .replaceAll('Đại lý', 'Tác nhân').replaceAll('đại lý', 'tác nhân')
      .replaceAll('Người đại diện', 'Tác nhân').replaceAll('người đại diện', 'tác nhân');
  }
  if (/personagem/i.test(key)) out = out.replaceAll('ký tự', 'nhân vật');
  return out;
}

